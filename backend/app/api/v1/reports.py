@router.get("/docx/{rfp_id}")
def export_docx_report(rfp_id: int, db: Session = Depends(get_db)) -> Response:
    """Generate and stream a professionally formatted Microsoft Word (.docx) Bid Report."""
    import docx
    from docx.shared import Inches, Pt, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.enum.table import WD_TABLE_ALIGNMENT

    rfp = db.query(RFP).filter(RFP.id == rfp_id).first()
    if not rfp:
        raise HTTPException(status_code=404, detail="RFP not found.")

    analysis = db.query(Analysis).filter(Analysis.rfp_id == rfp_id).first()
    reqs = db.query(Requirement).filter(Requirement.analysis_id == analysis.id).all() if analysis else []

    doc = docx.Document()

    # Document Header
    header = doc.add_heading("BIDWISE AI — EXECUTIVE PROPOSAL REPORT", level=0)
    header.alignment = WD_ALIGN_PARAGRAPH.CENTER

    sub = doc.add_paragraph("Comprehensive Multi-Agent Analysis, Risk Audit & Go/No-Go Bid Recommendation")
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER

    doc.add_paragraph()  # Spacer

    # Executive Metadata Table
    meta_table = doc.add_table(rows=6, cols=2)
    meta_table.alignment = WD_TABLE_ALIGNMENT.CENTER
    meta_table.style = "Light Grid Accent 1" if "Light Grid Accent 1" in [s.name for s in doc.styles] else "Table Grid"

    raw_meta = analysis.raw_response.get("metadata", {}) if analysis and isinstance(analysis.raw_response, dict) else {}
    telemetry = analysis.raw_response.get("telemetry", {}) if analysis and isinstance(analysis.raw_response, dict) else {}

    rec = telemetry.get("bid_recommendation") or (analysis.raw_response.get("analysis", {}).get("bid_recommendation") if analysis else "Review Required")
    readiness = telemetry.get("readiness_score") or (int((analysis.confidence_score or 0.85) * 100) if analysis else 85)
    win_prob = telemetry.get("win_probability_percent", 70)

    rows_data = [
        ("Document Title", rfp.title),
        ("Customer / Client", rfp.customer_name or "Enterprise Customer"),
        ("Submission Deadline", analysis.submission_deadline if analysis else "TBD"),
        ("Estimated Budget", analysis.budget if analysis else "TBD"),
        ("Overall Risk Level", analysis.overall_risk_score if analysis else "Medium"),
        ("Bid Recommendation", f"{rec} (Readiness: {readiness}/100 | Win Probability: {win_prob}%)")
    ]

    for idx, (label, val) in enumerate(rows_data):
        row = meta_table.rows[idx]
        cell_label = row.cells[0]
        cell_val = row.cells[1]
        cell_label.text = label
        cell_val.text = str(val or "N/A")
        cell_label.paragraphs[0].runs[0].font.bold = True

    doc.add_paragraph()  # Spacer

    # Section 1: Executive Summary
    doc.add_heading("1. Project Overview & Executive Summary", level=1)
    doc.add_paragraph(analysis.executive_summary if analysis and analysis.executive_summary else "No executive summary recorded.")

    # Section 2: Opportunity Summary & Scope
    doc.add_heading("2. Business Opportunity Scope", level=1)
    doc.add_paragraph(analysis.opportunity_summary if analysis and analysis.opportunity_summary else "Core enterprise technology modernization and digital services deployment.")

    # Section 3: Bid Recommendation & Strategic Rationale
    doc.add_heading("3. Strategic Bid Recommendation & Rationale", level=1)
    rec_rationale = (
        analysis.raw_response.get("analysis", {}).get("recommendation_rationale")
        if analysis and isinstance(analysis.raw_response, dict)
        else "Multi-agent evaluation completed based on organizational fit and contractual liability exposure."
    )
    doc.add_paragraph(rec_rationale)

    # Section 4: Compliance & Requirements Matrix
    doc.add_heading(f"4. Extracted Requirements Matrix ({len(reqs)} Total)", level=1)
    if reqs:
        req_table = doc.add_table(rows=len(reqs) + 1, cols=4)
        req_table.alignment = WD_TABLE_ALIGNMENT.CENTER
        req_table.style = "Table Grid"

        hdr_cells = req_table.rows[0].cells
        hdr_cells[0].text = "#"
        hdr_cells[1].text = "Category"
        hdr_cells[2].text = "Priority"
        hdr_cells[3].text = "Requirement Statement"
        for c in hdr_cells:
            c.paragraphs[0].runs[0].font.bold = True

        for i, r in enumerate(reqs, start=1):
            row_cells = req_table.rows[i].cells
            row_cells[0].text = str(i)
            row_cells[1].text = r.category or "Technical"
            row_cells[2].text = r.priority or "Medium"
            row_cells[3].text = r.requirement_text

    doc.add_paragraph()
    footer_p = doc.add_paragraph("Generated autonomously by BidWise AI Enterprise Platform")
    footer_p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    if footer_p.runs:
        footer_p.runs[0].font.italic = True
        footer_p.runs[0].font.size = Pt(9)

    docx_stream = io.BytesIO()
    doc.save(docx_stream)
    docx_bytes = docx_stream.getvalue()

    filename = f"BidWise_Executive_Report_RFP_{rfp_id}.docx"
    return Response(
        content=docx_bytes,
        media_type="application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        headers={"Content-Disposition": f"attachment; filename={filename}"},
    )


@router.get("/pdf")
def export_all_pdf(db: Session = Depends(get_db)) -> Response:
    """Generate overall summary report for all RFPs."""
    rfps = db.query(RFP).all()
    
    text_lines = ["========================================================================",
                  "BIDWISE AI — PORTFOLIO EXECUTIVE REPORT",
                  "========================================================================",
                  f"Total RFPs Processed: {len(rfps)}",
                  ""]

    for rfp in rfps:
        analysis = db.query(Analysis).filter(Analysis.rfp_id == rfp.id).first()
        text_lines.append(f"• [{rfp.id}] {rfp.title}")
        text_lines.append(f"  Customer: {rfp.customer_name or 'Enterprise'} | Risk: {analysis.overall_risk_score if analysis else 'Medium'} | Deadline: {analysis.submission_deadline if analysis else 'TBD'}")
        text_lines.append(f"  Summary: {analysis.executive_summary[:200] if analysis else ''}...")
        text_lines.append("")

    report_text = "\n".join(text_lines)
    return Response(
        content=report_text,
        media_type="text/plain",
        headers={"Content-Disposition": "attachment; filename=Portfolio_Executive_Report.txt"},
    )
